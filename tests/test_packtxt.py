@pytest.mark.parametrize("tag,bits", [
    ('<FULLSIZE>', 0x02),
    ('<ADD>',      0x04),
    ('<BG>',       0x08),
    ('<BUMP>',     0x10),
    ('<DUDV>',     0x20),
    ('<REFL>',     0x40),
])
def test_tag_flag_bits(tag, bits):
    cfg = parse_pack_txt_text(f"exported\n\n16\n{tag}\nprobe*\n")
    assert cfg.buckets[0].base_flags == bits
    assert cfg.buckets[0].alpha_override is None


def test_tags_may_share_a_line_and_combine():
    cfg = parse_pack_txt_text("exported\n\n16\n<ADD><BG>\nprobe*\n")
    assert cfg.buckets[0].base_flags == 0x0C


def test_alpha_and_opaque_are_overrides_not_bits():
    on = parse_pack_txt_text("exported\n\n16\n<ALPHA>\np*\n").buckets[0]
    off = parse_pack_txt_text("exported\n\n16\n<OPAQUE>\np*\n").buckets[0]
    assert on.base_flags == 0 and on.alpha_override is True
    assert off.base_flags == 0 and off.alpha_override is False
    # <OPAQUE> wins if both are present - it is the "never mind the pixels" tag
    both = parse_pack_txt_text("exported\n\n16\n<ALPHA><OPAQUE>\np*\n").buckets[0]
    assert both.alpha_override is False


def test_unknown_tags_are_reported_not_silently_dropped():
    b = parse_pack_txt_text("exported\n\n16\n<NOPE>\np*\n").buckets[0]
    assert b.unknown_tags == ('<NOPE>',)
    assert b.base_flags == 0


