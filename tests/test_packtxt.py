def test_alpha_thresholds_match_the_measured_utils_exe_constants():
    assert PACK_TXT_TRANSPARENT_MAX_ALPHA == 8
    assert PACK_TXT_OPAQUE_MIN_ALPHA == 230
    assert PACK_TXT_ALPHA_ENABLE_RATIO == 0.15


def test_alpha_enable_ratio_is_strictly_greater_than():
    """utils.exe: 1500/10000 stays opaque, 1501/10000 enables alpha."""
    assert group_alpha_enabled(1500, 10000) is False
    assert group_alpha_enabled(1501, 10000) is True
    assert group_alpha_enabled(0, 0) is False


def _png(tmp_path, name, alphas):
    """A 1xN RGBA PNG with the given alpha values."""
    a = np.asarray(alphas, dtype=np.uint8)
    rgb = np.full((len(a), 3), 200, dtype=np.uint8)
    img = np.concatenate([rgb, a[:, None]], axis=1).reshape(1, len(a), 4)
    path = tmp_path / f'{name}.png'
    Image.fromarray(img, 'RGBA').save(path)
    return path


def test_sprite_alpha_counts_uses_the_measured_cutoffs(tmp_path):
    """alpha<=8 is invisible, alpha>=230 is opaque, the rest is anti-aliasing."""
    p = _png(tmp_path, 's', [0, 8, 9, 128, 229, 230, 255])
    assert sprite_alpha_counts(p) == (3, 5)      # 9,128,229 semi of 5 visible


def test_group_alpha_is_pooled_over_the_whole_bucket(tmp_path):
    """One clean frame in a bucket does not lose the group its ALPHA flag —
    utils.exe pools the counters per palette, not per sprite (transit_w_new_*
    in the corpus: 17 anti-aliased frames + 1 hard-edged, all flagged)."""
    cfg = parse_pack_txt_text("exported\n\n16\nsoft_*\n")
    _png(tmp_path, 'soft_00', [128] * 50 + [255] * 50)      # 50 % semi
    _png(tmp_path, 'soft_01', [255] * 100)                  # 0 % semi
    flags = resolve_sprite_flags(cfg, tmp_path, ['soft_00', 'soft_01'])
    assert flags == {'soft_00': int(SpriteFlag.ALPHA),
                     'soft_01': int(SpriteFlag.ALPHA)}


def test_group_below_the_ratio_gets_no_alpha(tmp_path):
    cfg = parse_pack_txt_text("exported\n\n16\nhard_*\n")
    _png(tmp_path, 'hard_00', [128] * 15 + [255] * 85)      # exactly 15 %
    assert resolve_sprite_flags(cfg, tmp_path, ['hard_00']) == {'hard_00': 0}
    _png(tmp_path, 'hard_01', [128] * 16 + [255] * 84)      # 16 %
    assert resolve_sprite_flags(cfg, tmp_path, ['hard_01']) == \
        {'hard_01': int(SpriteFlag.ALPHA)}


def test_alpha_tag_beats_the_auto_ratio_on_a_barely_soft_bucket(tmp_path):
    """The corpus's selectcube_* blocks: only 3.7 % anti-aliased pixels, so
    auto-detection would say no — <ALPHA> drops the threshold to zero and any
    anti-aliasing at all is then enough."""
    cfg = parse_pack_txt_text("exported\n\n256\n<ALPHA><FULLSIZE>\nsel_*\n")
    _png(tmp_path, 'sel_00', [128] * 3 + [255] * 97)
    assert resolve_sprite_flags(cfg, tmp_path, ['sel_00']) == \
        {'sel_00': int(SpriteFlag.ALPHA | SpriteFlag.FULLSIZE)}


def test_alpha_tag_does_not_force_a_bucket_with_no_anti_aliasing(tmp_path):
    """`<ALPHA>` is a lowered threshold, not an override — and the threshold
    is still a STRICT bound, so a block whose alpha channel is purely binary
    packs OPAQUE despite the tag.

    Measured on OCT_ladybug, whose art/!pack_pal.txt tags `eat_*`, `hit_*` and
    `reboun*` `<FULLSIZE><ALPHA>`: all three pool 0 semi-transparent pixels
    (0/29910, 0/23834, 0/4266), utils.exe's own bucket listing prints them
    "FULLSIZE" with no ALPHA, and all 14 of their sprites carry Flags 0x02 in
    the shipped container. utils.exe prints no decision line for them at all.
    """
    cfg = parse_pack_txt_text("exported\n\n128\n<ALPHA><FULLSIZE>\neat_*\n")
    _png(tmp_path, 'eat_00', [0] * 20 + [255] * 80)     # keyed, never blended
    assert resolve_sprite_flags(cfg, tmp_path, ['eat_00']) == \
        {'eat_00': int(SpriteFlag.FULLSIZE)}
    # one anti-aliased pixel anywhere in the pool is enough to flip it
    _png(tmp_path, 'eat_01', [128] + [255] * 99)
    assert resolve_sprite_flags(cfg, tmp_path, ['eat_00', 'eat_01']) == \
        {'eat_00': int(SpriteFlag.ALPHA | SpriteFlag.FULLSIZE),
         'eat_01': int(SpriteFlag.ALPHA | SpriteFlag.FULLSIZE)}


def test_alpha_tag_lowers_the_threshold_to_a_strict_zero():
    assert group_alpha_enabled(0, 10000, PACK_TXT_ALPHA_TAGGED_RATIO) is False
    assert group_alpha_enabled(1, 10000, PACK_TXT_ALPHA_TAGGED_RATIO) is True
    assert group_alpha_enabled(0, 0, PACK_TXT_ALPHA_TAGGED_RATIO) is False


def test_alpha_ratio_reflects_the_tag():
    auto = parse_pack_txt_text("exported\n\n16\np*\n").buckets[0]
    on = parse_pack_txt_text("exported\n\n16\n<ALPHA>\np*\n").buckets[0]
    off = parse_pack_txt_text("exported\n\n16\n<OPAQUE>\np*\n").buckets[0]
    assert auto.alpha_ratio == PACK_TXT_ALPHA_ENABLE_RATIO
    assert on.alpha_ratio == PACK_TXT_ALPHA_TAGGED_RATIO == 0.0
    assert off.alpha_ratio is None       # never, whatever the pixels say


def test_opaque_tag_overrides_a_soft_bucket(tmp_path):
    cfg = parse_pack_txt_text("exported\n\n16\n<OPAQUE>\nsoft_*\n")
    _png(tmp_path, 'soft_00', [128] * 90 + [255] * 10)
    assert resolve_sprite_flags(cfg, tmp_path, ['soft_00']) == {'soft_00': 0}
    assert group_alpha_enabled(9000, 10000, None) is False


def test_fullsize_flag_reaches_the_packed_header(tmp_path):
    """The whole point of Task 2 for Task 1: the tag must be in `flags` before
    build_header runs, because FULLSIZE also halves the pivot scale."""
    import struct

    from config import HDR_OFF_FLAGS, HDR_OFF_PIVOT_X, HDR_OFF_PIVOT_Y
    from pack_codec import EncoderPalette, pack_sprite

    cfg = parse_pack_txt_text("exported\n\n64\n<FULLSIZE>\nahover*\n")
    png = _png(tmp_path, 'ahover_00', [255] * 100)
    flags = resolve_sprite_flags(cfg, tmp_path, ['ahover_00'])['ahover_00']
    assert flags == int(SpriteFlag.FULLSIZE)

    pal = EncoderPalette([(0, 0, 0, 0), (200, 200, 200, 255)])
    blob = pack_sprite(str(png), pal, flags=flags,
                       layer_x=8, layer_y=0, pivot_rect=(80, 80, 2, 2))
    assert blob[HDR_OFF_FLAGS] == int(SpriteFlag.FULLSIZE)
    # golden ahover_00 pivot from OCT_get_started/art/packed/ahover_00.raw
    assert struct.unpack_from('<ff', blob, HDR_OFF_PIVOT_X) == (72.5, 80.5)
    assert HDR_OFF_PIVOT_Y == HDR_OFF_PIVOT_X + 4


