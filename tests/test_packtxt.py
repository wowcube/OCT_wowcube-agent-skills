def test_build_config_palettes_sizes_every_group_as_declared(tmp_path):
    from pack_codec import build_config_palettes, symbol_bitness_for_size

    cfg = parse_pack_txt_text(
        "exported\n\n256\n*\n\n4\nfont*\n\n129\nt_halftwist*\n")
    files = []
    for name in ('bg_00', 'font_a', 't_halftwist'):
        rng = np.random.default_rng(abs(hash(name)) % 2**32)
        arr = rng.integers(0, 256, size=(8, 8, 4), dtype=np.uint8)
        arr[:, :, 3] = 255
        p = tmp_path / f'{name}.png'
        Image.fromarray(arr, 'RGBA').save(p)
        files.append(str(p))

    assignments, palette_data, unmatched = build_config_palettes(files, cfg)
    assert unmatched == []
    assert [len(c) for c, _ in palette_data] == [256, 4, 129]
    assert [s for _, s in palette_data] == [8, 2, 8]
    assert symbol_bitness_for_size(129) == 8
    assert assignments['bg_00'][0] == 0
    assert assignments['font_a'][0] == 1
    assert assignments['t_halftwist'][0] == 2
    # index 0 of every palette stays the transparent slot
    for colors, _sym in palette_data:
        assert colors[0] == (0, 0, 0, 0)


def test_fresh_header_honours_the_group_symbol_bitness(tmp_path):
    """A 16-colour group must encode at 4 bits, not the 8-bit default.

    Before this, ``symbol_bitness_override`` only took effect on the
    header-reuse path, so every freshly packed sprite was written at 8 bits
    whatever its palette size — the corpus came out 26 % *larger* than
    utils.exe's pack instead of 7 % smaller.
    """
    import struct

    from config import HDR_OFF_COMPRESSION
    from pack_codec import EncoderPalette, pack_sprite

    png = _png(tmp_path, 's', [255] * 64)
    pal = EncoderPalette([(0, 0, 0, 0)] + [(i * 16, 0, 0, 255) for i in range(15)])

    wide = pack_sprite(str(png), pal)
    narrow = pack_sprite(str(png), pal, symbol_bitness_override=4)
    assert struct.unpack_from('<I', wide, HDR_OFF_COMPRESSION)[0] & 0xFF == 8
    assert struct.unpack_from('<I', narrow, HDR_OFF_COMPRESSION)[0] & 0xFF == 4
    assert len(narrow) < len(wide)


def test_reserved_placeholder_gets_a_real_palette_group(tmp_path):
    """utils.exe logs ``0  pal:0 (*)`` — the reserved 0.png is a member of the
    catch-all block, so its palette group must exist in the container (46
    groups / 500 index.bin records for the corpus, not 45 / 499)."""
    from pack_codec import build_config_palettes

    cfg = parse_pack_txt_text("exported\n\n256\n*\n\n4\nfont*\n")
    files = [str(_png(tmp_path, '0', [255] * 4)),
             str(_png(tmp_path, 'font_a', [255] * 4))]
    assignments, palette_data, unmatched = build_config_palettes(files, cfg)
    assert unmatched == []
    assert assignments['0'][0] == 0
    assert assignments['font_a'][0] == 1
    assert len(palette_data) == 2


def _args(**kw):
    import argparse
    base = dict(pack_config=None, no_pack_config=False, manifest=None,
                art_dir='.')
    base.update(kw)
    return argparse.Namespace(**base)


def test_manifest_wins_over_pack_txt(tmp_path, capsys):
    """Manifest-driven apps must be unaffected by a stray !pack.txt."""
    from pack import _resolve_pack_config

    (tmp_path / '!pack.txt').write_text("exported\n\n16\n*\n")
    assert _resolve_pack_config(
        _args(art_dir=str(tmp_path), manifest='plans/x_assets.json')) is None
    assert 'takes precedence' in capsys.readouterr().out


