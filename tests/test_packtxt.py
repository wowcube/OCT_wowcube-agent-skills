def test_parses_the_corpus_blocks():
    cfg = parse_pack_txt_text(CORPUS_PACK_TXT)
    assert cfg.exported_dir == 'exported'
    assert len(cfg.buckets) == 10
    assert [b.max_colors for b in cfg.buckets] == \
        [256, 16, 256, 256, 16, 4, 129, 64, 64, 16]
    assert [b.index for b in cfg.buckets] == list(range(10))


def test_catch_all_bucket_is_first_and_matches_everything():
    cfg = parse_pack_txt_text(CORPUS_PACK_TXT)
    catch_all = cfg.buckets[0]
    assert catch_all.patterns == ('*',)
    assert catch_all.max_colors == 256
    assert catch_all.tags == ()
    # the reserved 0.png placeholder matches nothing else
    assert cfg.bucket_for('0') is catch_all
    assert cfg.assign('0') == (0, 256, 0)


def test_multiple_globs_share_one_bucket():
    cfg = parse_pack_txt_text(CORPUS_PACK_TXT)
    eyes = cfg.buckets[5]
    assert eyes.max_colors == 4
    assert eyes.patterns == ('eyes_idle*', 'eyesappear_*',
                             'eyesblink_*', 'eyeshappy_*')
    for name in ('eyes_idle_00', 'eyesappear_07', 'eyesblink_03', 'eyeshappy_1'):
        assert cfg.bucket_for(name) is eyes


def test_later_more_specific_mask_wins():
    """selectcube_transit_00 matches both selectcube_* and its own block."""
    cfg = parse_pack_txt_text(CORPUS_PACK_TXT)
    assert cfg.assign('selectcube_00') == (
        2, 256, int(SpriteFlag.ALPHA | SpriteFlag.FULLSIZE))
    assert cfg.assign('selectcube_orange_00') == (
        3, 256, int(SpriteFlag.ALPHA | SpriteFlag.FULLSIZE))
    # ... but the later 16-colour block takes the transit frames back, and
    # with them the FULLSIZE tag
    assert cfg.assign('selectcube_transit_00') == (4, 16, 0)


def test_fullsize_tag_sets_the_flag():
    cfg = parse_pack_txt_text(CORPUS_PACK_TXT)
    for name in ('ahover_00', 'ico_get_started'):
        group, colors, flags = cfg.assign(name)
        assert colors == 64
        assert flags == int(SpriteFlag.FULLSIZE)
        assert not flags & int(SpriteFlag.ALPHA)


def test_a_sprite_matching_nothing_falls_out_of_every_bucket():
    """utils.exe prints 'Unmatched palette %s, skipped'. Without a catch-all
    block there is simply no assignment."""
    cfg = parse_pack_txt_text("exported\n\n16\nfont*\n")
    assert cfg.bucket_for('coin_00') is None
    assert cfg.assign('coin_00') is None
    groups, unmatched = cfg.group_sprites(['font_a', 'coin_00'])
    assert groups == {0: ['font_a']}
    assert unmatched == ['coin_00']


def test_generated_pack_pal_txt_grammar():
    """A bare number *inside* a block is a sprite name, not a new block."""
    cfg = parse_pack_txt_text(CORPUS_PACK_PAL_TXT)
    assert len(cfg.buckets) == 3
    font = cfg.buckets[1]
    assert (font.max_colors, font.patterns) == (4, ('font*',))
    assert font.base_flags == int(SpriteFlag.FULLSIZE)
    third = cfg.buckets[2]
    assert third.max_colors == 32
    assert third.patterns == ('0', 'dot', 'carr*', 'rabb*', 'eyes_*')
    # "0" and "dot" carry no wildcard: they match exactly
    assert cfg.bucket_for('0') is third
    assert cfg.bucket_for('dot') is third
    assert cfg.bucket_for('dot2') is cfg.buckets[0]


def test_bom_and_crlf_are_tolerated(tmp_path):
    p = tmp_path / '!pack.txt'
    p.write_bytes(b'\xef\xbb\xbfexported\r\n\r\n16\r\nfont*\r\n')
    cfg = parse_pack_txt(p)
    assert cfg.exported_dir == 'exported'
    assert cfg.buckets[0].patterns == ('font*',)
    assert cfg.path == p


def test_find_pack_txt(tmp_path):
    assert find_pack_txt(tmp_path) is None
    (tmp_path / '!pack.txt').write_text("exported\n\n16\n*\n")
    assert find_pack_txt(tmp_path) == tmp_path / '!pack.txt'


@pytest.mark.parametrize("text,fragment", [
    ("", "empty config"),
    ("256\n\n*\n", "expected the exported-folder name"),
    ("exported\n\n16\n*\n\nfont*\n16\n", "expected a palette size"),
    ("exported\n\n16\n", "has no filename mask"),
    ("exported\n\n0\n*\n", "palette size must be >= 1"),
    ("exported\n\n16\n<ALPHA> junk\n*\n", "malformed tag line"),
])
def test_malformed_configs_are_rejected(text, fragment):
    with pytest.raises(PackTxtError) as exc:
        parse_pack_txt_text(text)
    assert fragment in str(exc.value)


