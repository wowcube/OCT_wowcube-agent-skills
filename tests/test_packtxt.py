"""``!pack.txt`` parsing, routing and per-group flags — utils.exe parity.

Ground truth for everything asserted here:

* the two real config files of the ``OCT_get_started`` corpus,
  ``art/!pack.txt`` (hand-tuned, 46 palette blocks) and ``art/!pack_pal.txt``
  (generated by ``art/pack_palettes.py``, which documents the same grammar in
  prose) — quoted verbatim in the fixtures below;
* the tag vocabulary read out of the reference ``utils.exe``
  (``<FULLSIZE> <BG> <ADD> <BUMP> <REFL> <DUDV> <ALPHA> <OPAQUE>``) and the
  flag bit each one sets, measured by packing a probe sprite per tag and
  reading octBmp_t offset 44 back;
* the ALPHA auto-detection thresholds, pinned by binary-searching the same
  ``utils.exe`` with synthetic sprites (see :mod:`config`).

The corpus itself is read-only and gitignored, so the numbers are pinned here
rather than read at test time.
"""
